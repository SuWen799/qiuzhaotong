const VALID_RECRUIT_TYPES = ['春招', '秋招', '秋招提前批', '春招提前批', '实习'];

// Sunwz|2026-10-22|改动目的：招聘类型模糊推断——RECRUIT_TYPE_MAP 精确匹配不到时按关键词兜底，
// 避免"秋招专场"这类变体被整段丢弃导致招聘类型为空（空值行在招聘类型筛选下永远不可见）。
function inferRecruitType(part) {
    if (!part) return null;
    if (part.includes('提前批')) return '秋招提前批';
    if (part.includes('实习')) return '实习';
    if (part.includes('秋招') || part.includes('校招') || part.includes('校园招聘')) return '秋招';
    if (part.includes('春招')) return '春招';
    return null;
}

function normalizeRecruitType(value) {
    if (!value) return [];
    value = value.replace(/[�]/g, '').trim();
    if (value.length < 2 || value.includes('筛选') || value.includes('必读')) return [];

    const parts = value.split(/[,，/]/).map(s => s.trim()).filter(Boolean);
    const results = [];

    for (const part of parts) {
        const mapped = RECRUIT_TYPE_MAP[part];
        if (mapped && !results.includes(mapped)) {
            results.push(mapped);
        } else if (!mapped && !results.includes(part)) {
            // 不在映射表中的类型：先模糊推断（Sunwz|2026-10-22），标准类型直接保留，否则跳过
            const guessed = inferRecruitType(part);
            if (guessed) {
                if (!results.includes(guessed)) results.push(guessed);
            } else if (VALID_RECRUIT_TYPES.includes(part)) {
                results.push(part);
            }
        }
    }

    return results;
}
