function normalizeIndustry(value) {
    if (!value) return [];
    value = value.replace(/[�]/g, '').trim();
    if (value.length < 2 || value.includes('必看') || value.includes('申请')) return ['其他'];

    // 制造-* 统一为制造业
    if (value.startsWith('制造')) return ['制造业'];

    // 分割多值
    const parts = value.split(/[,，/]/).map(s => s.trim()).filter(Boolean);
    const results = [];

    for (const part of parts) {
        if (part.startsWith('制造')) {
            if (!results.includes('制造业')) results.push('制造业');
            continue;
        }
        let matched = false;
        for (const [keyword, category] of Object.entries(INDUSTRY_MAP)) {
            if (part.includes(keyword)) {
                if (!results.includes(category) && MAJOR_INDUSTRIES.has(category)) {
                    results.push(category);
                }
                matched = true;
                break;
            }
        }
        // 不在主要类别中的归为"其他"
        if (!matched && MAJOR_INDUSTRIES.has(part)) {
            results.push(part);
        }
    }

    // 如果没有匹配到任何主要类别，归为"其他"
    if (results.length === 0) return ['其他'];

    return results;
}

function normalizeTarget(value) {
    if (!value) return [];
    value = value.replace(/[�]/g, '').trim();

    // 提取年份
    const years = new Set();
    const patterns = [/(20\d{2})届/g, /(20\d{2})年毕业生/g, /(20\d{2})/g];
    for (const pattern of patterns) {
        let match;
        while ((match = pattern.exec(value)) !== null) {
            years.add(match[1] + '届');
        }
    }

    const results = [...years];

    // 特殊标记
    if (value.includes('海外')) results.push('海外');
    if (value.includes('往届')) results.push('往届');

    // 只保留 2025-2027 届，其他归为"其他"
    const validYears = results.filter(y => ['2025届', '2026届', '2027届'].includes(y));
    const others = results.filter(y => !['2025届', '2026届', '2027届'].includes(y));

    const final = [...validYears];
    if (others.length > 0) final.push('其他');

    return final.length > 0 ? final : ['其他'];
}

