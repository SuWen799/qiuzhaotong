'use strict';
/**
 * crawlers/douyin_cookies.js
 * 用 msedge 持久化 profile 打开抖音页面，把该上下文里的全部 cookie 导出为
 * Netscape 格式 cookies.txt，供 yt-dlp --cookies 使用。
 * （抖音接口要求 "fresh cookies, not necessarily logged in"，匿名 cookie 即可）
 *
 * 用法: node douyin_cookies.js <抖音链接> [cookies输出路径]
 */
const fs = require('fs');
const path = require('path');
const { safeLaunchPersistentContext } = require('./utils/launchProfile.js');

const url = process.argv[2];
if (!url) {
  console.error('usage: node douyin_cookies.js <url> [cookies.txt]');
  process.exit(1);
}
const outFile = process.argv[3] || path.resolve(__dirname, '../../outputs/douyin/cookies.txt');
const PROFILE_DIR = path.resolve(__dirname, '../data/douyin-profile');

(async () => {
  const ctx = await safeLaunchPersistentContext(
    PROFILE_DIR,
    {
      channel: 'msedge',
      headless: false,
      locale: 'zh-CN',
      args: ['--disable-blink-features=AutomationControlled']
    },
    'douyin'
  );

  const page = ctx.pages()[0] || (await ctx.newPage());
  try {
    await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 });
    await page.waitForTimeout(5000);
  } catch (e) {
    console.error('goto err:', e.message);
  }

  const cookies = await ctx.cookies();
  const lines = ['# Netscape HTTP Cookie File', '# generated by douyin_cookies.js', ''];
  for (const c of cookies) {
    if (!c.name || c.value === undefined) continue;
    const flag = c.domain && c.domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    const expiry = c.expires && c.expires > 0 ? Math.floor(c.expires) : 0;
    lines.push([c.domain, flag, c.path || '/', secure, expiry, c.name, c.value].join('\t'));
  }

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, lines.join('\n'), 'utf8');

  console.log('COOKIE_COUNT:', cookies.length);
  console.log('COOKIE_NAMES:', cookies.map((c) => c.name).join(', '));
  console.log('COOKIES_FILE:', outFile);

  await ctx.close();
})().catch((e) => {
  console.error('FATAL', e);
  process.exit(1);
});
